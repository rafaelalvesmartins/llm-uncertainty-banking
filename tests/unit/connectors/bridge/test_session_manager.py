class TestResolveEscalate:
    def setup_method(self) -> None:
        self.m = SessionManager(InMemorySessionStore())

    def test_resolve_marks_session(self) -> None:
        s = self.m.start("c-1", Channel.MOBILE_APP)
        self.m.resolve(s.session_id)
