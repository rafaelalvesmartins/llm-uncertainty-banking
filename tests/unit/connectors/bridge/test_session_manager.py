class TestHistoryAndMetrics:
    def test_history_returns_chat_format(self) -> None:
        m = SessionManager(InMemorySessionStore())
        s = m.start("c-1", Channel.MOBILE_APP)
        m.append(s.session_id, MessageRole.USER, "hi")
        m.append(s.session_id, MessageRole.ASSISTANT, "hello")
        h = m.history(s.session_id)
        assert h == [
            {"role": "user", "content": "hi"},
            {"role": "assistant", "content": "hello"},
        ]

    def test_metrics_empty_store(self) -> None:
        m = SessionManager(InMemorySessionStore())
        metrics = m.metrics()
        assert isinstance(metrics, SessionMetrics)
        assert metrics.total == 0
        assert metrics.retention_rate == 0.0

    def test_metrics_resolved_counts(self) -> None:
        m = SessionManager(InMemorySessionStore())
        s1 = m.start("c-1", Channel.MOBILE_APP)
        s2 = m.start("c-2", Channel.WHATSAPP)
        s3 = m.start("c-3", Channel.WEB)
        m.resolve(s1.session_id)
        m.resolve(s2.session_id)
        m.escalate(s3.session_id, "low_conf")
        metrics = m.metrics()
        assert metrics.total == 3
        assert metrics.resolved == 2
        assert metrics.escalated == 1
        # 2 resolved out of 3 closed = 66.7%
        assert metrics.retention_rate == pytest.approx(2 / 3, abs=0.01)

    def test_metrics_by_channel_breakdown(self) -> None:
        m = SessionManager(InMemorySessionStore())
        m.start("c-1", Channel.MOBILE_APP)
        m.start("c-2", Channel.MOBILE_APP)
        m.start("c-3", Channel.WHATSAPP)
        metrics = m.metrics()
        assert metrics.by_channel == {"mobile_app": 2, "whatsapp": 1}

    def test_metrics_open_sessions_counted(self) -> None:
        m = SessionManager(InMemorySessionStore())
        m.start("c-1", Channel.MOBILE_APP)
        m.start("c-2", Channel.WEB)
        metrics = m.metrics()
        assert metrics.open_sessions == 2


