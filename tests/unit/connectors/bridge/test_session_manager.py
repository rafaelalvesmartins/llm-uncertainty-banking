class TestIdleExpiry:
    def test_idle_session_gets_escalated(self) -> None:
        m = SessionManager(InMemorySessionStore(), ttl=timedelta(seconds=60))
        s = m.start("c-1", Channel.MOBILE_APP)
        # Force a stale last_active_at
        stored = m.get(s.session_id)
        stored.last_active_at = datetime.now(UTC) - timedelta(hours=1)
        m._store.put(stored)

        expired = m.expire_idle()
        assert s.session_id in expired
        assert m.get(s.session_id).escalated is True

    def test_fresh_session_not_expired(self) -> None:
        m = SessionManager(InMemorySessionStore(), ttl=timedelta(hours=1))
        s = m.start("c-1", Channel.MOBILE_APP)
        expired = m.expire_idle()
        assert s.session_id not in expired

    def test_resolved_sessions_skipped(self) -> None:
        m = SessionManager(InMemorySessionStore(), ttl=timedelta(seconds=10))
        s = m.start("c-1", Channel.MOBILE_APP)
        m.resolve(s.session_id)
        # Even with stale timestamp, resolved sessions are skipped
        stored = m.get(s.session_id)
        stored.last_active_at = datetime.now(UTC) - timedelta(hours=1)
        m._store.put(stored)
        expired = m.expire_idle()
        assert s.session_id not in expired


