class TestSessionLifecycle:
    def setup_method(self) -> None:
        self.m = SessionManager(InMemorySessionStore())

    def test_start_creates_session(self) -> None:
        s = self.m.start("c-1", Channel.WHATSAPP)
        assert s.customer_id == "c-1"
        assert s.channel == Channel.WHATSAPP
        assert s.session_id  # autogenerated UUID

    def test_start_with_explicit_session_id(self) -> None:
        s = self.m.start("c-1", Channel.WEB, session_id="my-id")
        assert s.session_id == "my-id"

    def test_start_with_system_prompt_appends_message(self) -> None:
        s = self.m.start("c-1", Channel.MOBILE_APP, system_prompt="Voce e o Bridge")
        assert len(s.messages) == 1
        assert s.messages[0].role == MessageRole.SYSTEM
        assert s.messages[0].content == "Voce e o Bridge"

    def test_start_with_metadata(self) -> None:
        s = self.m.start("c-1", Channel.MOBILE_APP, metadata={"region": "SP"})
        assert s.metadata == {"region": "SP"}

    def test_get_returns_started_session(self) -> None:
        s = self.m.start("c-1", Channel.MOBILE_APP)
        assert self.m.get(s.session_id).session_id == s.session_id

    def test_get_unknown_raises(self) -> None:
        with pytest.raises(SessionNotFoundError):
            self.m.get("does-not-exist")

    def test_append_adds_to_messages(self) -> None:
        s = self.m.start("c-1", Channel.MOBILE_APP)
        self.m.append(s.session_id, MessageRole.USER, "qual saldo?")
        self.m.append(s.session_id, MessageRole.ASSISTANT, "R$ 100")
        out = self.m.get(s.session_id)
        assert len(out.messages) == 2

    def test_append_to_resolved_raises(self) -> None:
        s = self.m.start("c-1", Channel.MOBILE_APP)
        self.m.resolve(s.session_id)
        with pytest.raises(ValueError, match="closed session"):
            self.m.append(s.session_id, MessageRole.USER, "another")

    def test_append_to_escalated_raises(self) -> None:
        s = self.m.start("c-1", Channel.MOBILE_APP)
        self.m.escalate(s.session_id, "test")
        with pytest.raises(ValueError, match="closed session"):
            self.m.append(s.session_id, MessageRole.USER, "another")


