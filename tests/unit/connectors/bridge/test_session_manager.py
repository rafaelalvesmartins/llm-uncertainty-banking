class TestInMemoryStore:
    def test_put_and_get(self) -> None:
        store = InMemorySessionStore()
        s = Session(session_id="x", customer_id="c-1", channel=Channel.MOBILE_APP)
        store.put(s)
        assert store.get("x") is not None

    def test_get_missing_raises(self) -> None:
        store = InMemorySessionStore()
        with pytest.raises(SessionNotFoundError):
            store.get("nope")

    def test_delete_present(self) -> None:
        store = InMemorySessionStore()
        s = Session(session_id="x", customer_id="c-1", channel=Channel.MOBILE_APP)
        store.put(s)
        store.delete("x")
        with pytest.raises(SessionNotFoundError):
            store.get("x")

    def test_delete_missing_silent(self) -> None:
        # Per docstring: 'silently ignore an unknown id' (LGPD right-to-erasure path).
        InMemorySessionStore().delete("nope")  # should not raise

    def test_list_for_customer_filters(self) -> None:
        store = InMemorySessionStore()
        store.put(Session(session_id="a", customer_id="c-1", channel=Channel.MOBILE_APP))
        store.put(Session(session_id="b", customer_id="c-1", channel=Channel.WEB))
        store.put(Session(session_id="c", customer_id="c-2", channel=Channel.MOBILE_APP))
        c1 = store.list_for_customer("c-1")
        assert len(c1) == 2
        assert all(s.customer_id == "c-1" for s in c1)

    def test_all_sessions(self) -> None:
        store = InMemorySessionStore()
        store.put(Session(session_id="a", customer_id="c-1", channel=Channel.MOBILE_APP))
        store.put(Session(session_id="b", customer_id="c-2", channel=Channel.WEB))
        assert len(store.all_sessions()) == 2


