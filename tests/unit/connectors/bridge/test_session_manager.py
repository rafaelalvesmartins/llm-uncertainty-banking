class TestSerialization:
    def test_session_to_dict_round_trip(self) -> None:
        s = Session(session_id="x", customer_id="c-1", channel=Channel.MOBILE_APP)
        s.append(Message(role=MessageRole.USER, content="hi"))
        s.append(Message(role=MessageRole.ASSISTANT, content="hello"))
        d = s.to_dict()
        s2 = Session.from_dict(d)
        assert s2.session_id == s.session_id
        assert s2.customer_id == s.customer_id
        assert len(s2.messages) == 2

    def test_message_to_dict_round_trip(self) -> None:
        m = Message(role=MessageRole.USER, content="hi", metadata={"channel": "x"})
        d = m.to_dict()
        m2 = Message.from_dict(d)
        assert m2.role == m.role
        assert m2.content == m.content
        assert m2.metadata == m.metadata

    def test_session_duration(self) -> None:
        s = Session(
            session_id="x",
            customer_id="c-1",
            channel=Channel.MOBILE_APP,
            started_at=datetime(2026, 1, 1, 12, 0, tzinfo=UTC),
            last_active_at=datetime(2026, 1, 1, 12, 5, tzinfo=UTC),
        )
        assert s.duration == timedelta(minutes=5)
