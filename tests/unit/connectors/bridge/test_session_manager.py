"""Coverage-focused tests for ``lub.connectors.bridge.session.SessionManager``.

Targets the SessionManager facade + InMemorySessionStore happy paths and
the lifecycle policy (TTL expiry, resolution, escalation, metrics) so
the audit/retention numbers the platform reports come from a tested
code path.
"""

from __future__ import annotations

from datetime import UTC, datetime, timedelta

import pytest

from lub.connectors.bridge.session import (
    Channel,
    InMemorySessionStore,
    Message,
    MessageRole,
    Session,
    SessionManager,
    SessionMetrics,
    SessionNotFoundError,
)

UTC = UTC


# ---------------------------------------------------------------------------
# Construction
# ---------------------------------------------------------------------------


class TestConstruction:
    def test_default_ttl_24h(self) -> None:
        m = SessionManager(InMemorySessionStore())
        assert m._ttl == timedelta(hours=24)

    def test_zero_ttl_raises(self) -> None:
        with pytest.raises(ValueError, match="ttl must be positive"):
            SessionManager(InMemorySessionStore(), ttl=timedelta(seconds=0))

    def test_negative_ttl_raises(self) -> None:
        with pytest.raises(ValueError):
            SessionManager(InMemorySessionStore(), ttl=timedelta(seconds=-1))

    def test_store_property(self) -> None:
        store = InMemorySessionStore()
        m = SessionManager(store)
        assert m.store is store


